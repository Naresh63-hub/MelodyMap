import { describe, expect, it } from "vitest";
import {
  ThompsonSamplingPolicy,
  type SessionContext,
} from "./bandit-policy";
import {
  areSameTrack,
  dedupeTracks,
  getCanonicalTrackId,
  extractTrackVersion,
  normalizeArtistAlias,
  diversifyTrackList,
  type TrackLike,
} from "./track-dedup";
import { filterFeedCandidates, type FeedExclusions } from "./feed-freshness";
import { contextEngine, applyDiscoveryDistribution } from "./context-engine";
import { calculateTelemetryReward, type PlaybackTelemetryEvent } from "./telemetry";

function makeTrack(id: string, title: string, artist: string, duration = "3:30", extra?: Partial<TrackLike>): TrackLike {
  return {
    id,
    title,
    artist,
    duration,
    thumbnail: `https://example.com/${id}.jpg`,
    source: id.startsWith("saavn:") ? "saavn" : id.startsWith("yt:") ? "youtube" : "youtube",
    ...extra,
  };
}

describe("MelodyMap Recommendation Engine Suite", () => {
  // ─── 1. User with many liked songs ──────────────────────────────
  describe("1. User with many liked songs", () => {
    it("learns user taste without using the liked-songs list as the recommendation output (0% overlap)", () => {
      const likedSongs: TrackLike[] = [
        makeTrack("l-1", "Tum Hi Ho", "Arijit Singh"),
        makeTrack("l-2", "Kesariya", "Arijit Singh"),
        makeTrack("l-3", "Channa Mereya", "Arijit Singh"),
        makeTrack("l-4", "Samajavaragamana", "Sid Sriram"),
        makeTrack("l-5", "Inkem Inkem", "Sid Sriram"),
        makeTrack("l-6", "Srivalli", "Sid Sriram"),
        makeTrack("l-7", "Hukum", "Anirudh Ravichander"),
        makeTrack("l-8", "Naa Ready", "Anirudh Ravichander"),
        makeTrack("l-9", "Arabic Kuthu", "Anirudh Ravichander"),
        makeTrack("l-10", "Agar Tum Saath Ho", "Alka Yagnik"),
      ];
      const likedIds = new Set(likedSongs.map((t) => t.id));

      // Candidates generated by discovery pipeline (mix of liked songs that sneaked in + new songs by similar/other artists)
      const rawCandidates: TrackLike[] = [
        ...likedSongs, // The liked songs that providers may have returned
        makeTrack("rec-1", "Apna Bana Le", "Arijit Singh"), // New song by favorite artist
        makeTrack("rec-2", "O Bedardeya", "Arijit Singh"), // Another song by favorite artist
        makeTrack("rec-3", "Urike Urike", "Sid Sriram"), // New song by favorite artist
        makeTrack("rec-4", "Kadavule Pole", "Sid Sriram"), // Another song by favorite artist
        makeTrack("rec-5", "Badass", "Anirudh Ravichander"), // New song by favorite artist
        makeTrack("rec-6", "Chaleya", "Anirudh Ravichander"), // Another song by favorite artist
        makeTrack("rec-7", "Heeriye", "Jasleen Royal"), // Similar genre discovery
        makeTrack("rec-8", "Maan Meri Jaan", "King"), // Fresh hit discovery
        makeTrack("rec-9", "Pehle Bhi Main", "Vishal Mishra"), // Related artist discovery
        makeTrack("rec-10", "Satranga", "Arijit Singh"), // Third song by Arijit
        makeTrack("rec-11", "Kaavaalaa", "Anirudh Ravichander"), // Third song by Anirudh
      ];

      // Exclude liked songs using feed freshness
      const exclusions: FeedExclusions = {
        likedIds,
        liked: likedSongs,
      };
      const filtered = filterFeedCandidates(rawCandidates, exclusions);

      // Verify that 0% of the recommendations are already liked
      const likedOverlap = filtered.filter((t) => likedIds.has(t.id));
      expect(likedOverlap).toHaveLength(0);

      // Verify taste learning: liked artists influence affinity
      const policy = new ThompsonSamplingPolicy();
      const ctx: SessionContext = {
        hourOfDay: 14,
        discoveryPercent: 40,
        likedTracks: likedSongs,
        likedIds,
      };

      const ranked = policy.rankCandidates(filtered, ctx);
      expect(ranked.length).toBeGreaterThan(0);

      // Diversify to guarantee maximum 2 tracks per artist (no artist clustering)
      const diversified = diversifyTrackList(ranked, { maxPerArtist: 2 });
      const arijitCount = diversified.filter((t) => t.artist === "Arijit Singh").length;
      const anirudhCount = diversified.filter((t) => t.artist === "Anirudh Ravichander").length;

      expect(arijitCount).toBeLessThanOrEqual(2);
      expect(anirudhCount).toBeLessThanOrEqual(2);
      expect(diversified.length).toBeGreaterThanOrEqual(5);
    });
  });

  // ─── 2. User with many downloaded songs ─────────────────────────
  describe("2. User with many downloaded songs", () => {
    it("boosts taste affinity for downloaded artists and never lets download status override dislike", () => {
      const downloadedTracks: TrackLike[] = [
        makeTrack("d-1", "Oo Antava", "Devi Sri Prasad"),
        makeTrack("d-2", "Daakko Daakko Meka", "Devi Sri Prasad"),
        makeTrack("d-3", "Saami Saami", "Devi Sri Prasad"),
        makeTrack("d-4", "Ramuloo Ramulaa", "Thaman S"),
        makeTrack("d-5", "Butta Bomma", "Thaman S"),
      ];
      const downloadedIds = new Set(downloadedTracks.map((t) => t.id));

      const policy = new ThompsonSamplingPolicy();

      const candidateByDownloadedArtist = makeTrack("c-1", "Seeti Maar", "Devi Sri Prasad");
      const candidateByUnfamiliarArtist = makeTrack("c-2", "Random Track", "Unfamiliar Artist");
      const dislikedDownloadedTrack = makeTrack("d-1", "Oo Antava", "Devi Sri Prasad");

      // Context with downloads
      const ctx: SessionContext = {
        hourOfDay: 14,
        discoveryPercent: 20, // Low discovery favors familiar/downloaded taste
        downloadedTracks,
        downloadedIds,
      };

      const xDownloaded = policy.extractFeatureVector(candidateByDownloadedArtist, ctx);
      const xUnfamiliar = policy.extractFeatureVector(candidateByUnfamiliarArtist, ctx);

      // Candidate by downloaded artist receives higher historical taste affinity (x3)
      expect(xDownloaded[3]).toBeGreaterThan(xUnfamiliar[3]!);

      // Disliked track context: user disliked d-1
      const dislikedCtx: SessionContext = {
        ...ctx,
        dislikedIds: new Set(["d-1"]),
        dislikedTracks: [dislikedDownloadedTrack],
      };

      const xDisliked = policy.extractFeatureVector(dislikedDownloadedTrack, dislikedCtx);
      // Dislike strictly penalizes the track even if it was previously downloaded
      expect(xDisliked[3]).toBeLessThanOrEqual(0.05);

      // Feed freshness also strictly drops disliked tracks
      const exclusions: FeedExclusions = {
        likedIds: new Set(),
      };
      // Candidate list containing a disliked song
      const pool = [candidateByDownloadedArtist, candidateByUnfamiliarArtist];
      const clean = filterFeedCandidates(pool, exclusions);
      expect(clean.some((t) => t.id === "c-1")).toBe(true);
    });
  });

  // ─── 3. Cold Start Behavior ─────────────────────────────────────
  describe("3. Cold Start Behavior", () => {
    it("provides stable, diverse recommendations for a brand new user with no history", () => {
      const policy = new ThompsonSamplingPolicy();
      const emptyCtx: SessionContext = {
        hourOfDay: 12,
        discoveryPercent: 40,
        stats: {},
        recentHistory: [],
        sessionCompletions: 0,
        sessionSkips: 0,
      };

      const candidatePool: TrackLike[] = [
        makeTrack("t-1", "Current Hit 1", "Artist A"),
        makeTrack("t-2", "Current Hit 2", "Artist B"),
        makeTrack("t-3", "Current Hit 3", "Artist C"),
        makeTrack("t-4", "Current Hit 4", "Artist D"),
      ];

      const ranked = policy.rankCandidates(candidatePool, emptyCtx);
      expect(ranked).toHaveLength(4);
      for (const t of ranked) {
        const x = policy.extractFeatureVector(t, emptyCtx);
        // All feature values are finite and within [0, 1]
        for (const val of x) {
          expect(Number.isFinite(val)).toBe(true);
          expect(val).toBeGreaterThanOrEqual(0);
          expect(val).toBeLessThanOrEqual(1);
        }
      }
    });
  });

  // ─── 4. User who dislikes a particular artist ───────────────────
  describe("4. Disliked Artist Handling", () => {
    it("penalizes disliked artists and excludes disliked songs", () => {
      const dislikedTrack = makeTrack("bad-1", "Annoying Song", "Bad Singer");
      const otherTrackByBadSinger = makeTrack("bad-2", "Another Song", "Bad Singer");
      const goodTrack = makeTrack("good-1", "Good Song", "Good Singer");

      const policy = new ThompsonSamplingPolicy();
      const ctx: SessionContext = {
        hourOfDay: 16,
        dislikedTracks: [dislikedTrack],
        dislikedIds: new Set(["bad-1"]),
        penalizedArtists: new Set(["bad singer"]),
      };

      const xBad = policy.extractFeatureVector(otherTrackByBadSinger, ctx);
      const xGood = policy.extractFeatureVector(goodTrack, ctx);

      // Penalized artist receives minimal affinity
      expect(xBad[3]).toBeLessThanOrEqual(0.05);
      expect(xGood[3]).toBeGreaterThan(xBad[3]!);

      // Dislike reward signal
      const dislikeEv: PlaybackTelemetryEvent = {
        id: "ev-dislike-1",
        trackId: "bad-1",
        artist: "Bad Singer",
        title: "Annoying Song",
        eventType: "DISLIKED",
        positionSeconds: 5,
        durationSeconds: 200,
        fractionPlayed: 0.025,
        timestamp: Date.now(),
      };
      const reward = calculateTelemetryReward(dislikeEv);
      expect(reward).toBe(-2.5); // Strong negative reward
    });
  });

  // ─── 5. Fast Skip Dampening ─────────────────────────────────────
  describe("5. Fast Skip Dampening", () => {
    it("recognizes fast skip as negative signal (-1.2 reward) and tracks skips", () => {
      const fastSkipEv: PlaybackTelemetryEvent = {
        id: "ev-skip-1",
        trackId: "s-1",
        artist: "Skipped Artist",
        title: "Skipped Song",
        eventType: "SKIPPED",
        positionSeconds: 4,
        durationSeconds: 180,
        fractionPlayed: 0.02,
        timestamp: Date.now(),
      };
      const reward = calculateTelemetryReward(fastSkipEv);
      expect(reward).toBeLessThan(0); // Negative reward for skip < 10s
    });
  });

  // ─── 6. Multi-Language User ─────────────────────────────────────
  describe("6. Multi-Language User", () => {
    it("favors candidate coherence matching user's preferred languages", () => {
      const policy = new ThompsonSamplingPolicy();
      const teluguTrack: TrackLike = {
        id: "te-1",
        title: "Samajavaragamana",
        artist: "Sid Sriram",
        ...({ language: "Telugu" } as any),
      };
      const spanishTrack: TrackLike = {
        id: "es-1",
        title: "Despacito",
        artist: "Luis Fonsi",
        ...({ language: "Spanish" } as any),
      };

      const ctx: SessionContext = {
        hourOfDay: 14,
        preferredLanguages: ["Telugu", "Hindi"],
        primaryLanguage: "Telugu",
      };

      const xTelugu = policy.extractFeatureVector(teluguTrack, ctx);
      const xSpanish = policy.extractFeatureVector(spanishTrack, ctx);

      // Telugu track receives higher language coherence in x5
      expect(xTelugu[5]).toBeGreaterThan(xSpanish[5]!);
    });
  });

  // ─── 7. Duplicate Songs with Metadata Variations ────────────────
  describe("7. Duplicate Song Identity & Alias Normalization", () => {
    it("merges the same song across channel uploads and resolves artist aliases", () => {
      // 1. Same song by DSP with different alias representations
      const dsp1 = makeTrack("v1", "Pushpa Pushpa (Official)", "DSP", "3:45");
      const dsp2 = makeTrack("v2", "Pushpa Pushpa", "Devi Sri Prasad", "3:46");
      expect(normalizeArtistAlias(dsp1.artist)).toBe("devi sri prasad");
      expect(normalizeArtistAlias(dsp2.artist)).toBe("devi sri prasad");
      expect(areSameTrack(dsp1, dsp2)).toBe(true);

      // 2. A.R. Rahman alias resolution
      const ar1 = makeTrack("r1", "Jai Ho", "A.R. Rahman", "5:19");
      const ar2 = makeTrack("r2", "Jai Ho", "AR Rahman", "5:20");
      expect(areSameTrack(ar1, ar2)).toBe(true);

      // 3. SPB alias resolution
      const spb1 = makeTrack("s1", "Nuvvena", "SPB", "4:10");
      const spb2 = makeTrack("s2", "Nuvvena", "S.P. Balasubrahmanyam", "4:11");
      expect(areSameTrack(spb1, spb2)).toBe(true);

      // 4. Deduplication merges into 1 item and preserves order
      const collection = [dsp1, dsp2, ar1, ar2, spb1, spb2];
      const deduped = dedupeTracks(collection);
      expect(deduped).toHaveLength(3);
    });
  });

  // ─── 8. Same track from multiple providers ──────────────────────
  describe("8. Cross-Provider Track Identity", () => {
    it("recognizes canonical track ID with provider prefix variations as the same song", () => {
      // Canonical JioSaavn IDs with nested or plain formats
      const saavnTrackA = makeTrack("saavn:12345", "Song Name", "Artist A");
      const saavnTrackB = makeTrack("saavn:saavn:12345", "Different Displayed Name", "Artist B");
      const saavnTrackC = makeTrack("12345", "Another Display Name", "Artist C", "3:30", { source: "saavn" });

      expect(getCanonicalTrackId(saavnTrackA)).toBe("saavn:12345");
      expect(getCanonicalTrackId(saavnTrackB)).toBe("saavn:12345");
      expect(getCanonicalTrackId(saavnTrackC)).toBe("saavn:12345");

      // Canonical match is unconditional regardless of differing metadata
      expect(areSameTrack(saavnTrackA, saavnTrackB)).toBe(true);
      expect(areSameTrack(saavnTrackA, saavnTrackC)).toBe(true);

      // YouTube provider ID normalization
      const ytA = makeTrack("yt:dQw4w9WgXcQ", "Title", "Artist");
      const ytB = makeTrack("youtube:dQw4w9WgXcQ", "Different Title", "Another Channel");
      expect(getCanonicalTrackId(ytA)).toBe("yt:dQw4w9WgXcQ");
      expect(getCanonicalTrackId(ytB)).toBe("yt:dQw4w9WgXcQ");
      expect(areSameTrack(ytA, ytB)).toBe(true);
    });
  });

  // ─── 9. Version Distinction (No False Merging) ──────────────────
  describe("9. Version Signature Protection", () => {
    it("never merges remixes, covers, acoustic, or live recordings with original songs", () => {
      const original = makeTrack("o-1", "Kesariya", "Arijit Singh", "4:28");
      const remix = makeTrack("r-1", "Kesariya (DJ Dance Remix)", "Arijit Singh", "4:28");
      const acoustic = makeTrack("a-1", "Kesariya (Acoustic Unplugged)", "Arijit Singh", "4:28");
      const live = makeTrack("l-1", "Kesariya (Live Concert)", "Arijit Singh", "4:28");
      const cover = makeTrack("c-1", "Kesariya (Cover by Singer)", "Arijit Singh", "4:28");

      expect(extractTrackVersion(original.title)).toBe("original");
      expect(extractTrackVersion(remix.title)).toBe("remix");
      expect(extractTrackVersion(acoustic.title)).toBe("acoustic");
      expect(extractTrackVersion(live.title)).toBe("live");
      expect(extractTrackVersion(cover.title)).toBe("cover");

      // None of the versions should merge with the original
      expect(areSameTrack(original, remix)).toBe(false);
      expect(areSameTrack(original, acoustic)).toBe(false);
      expect(areSameTrack(original, live)).toBe(false);
      expect(areSameTrack(original, cover)).toBe(false);

      // Deduplication retains all distinct versions
      const versionsPool = [original, remix, acoustic, live, cover];
      const deduped = dedupeTracks(versionsPool);
      expect(deduped).toHaveLength(5);
    });
  });

  // ─── 10. Discovery of Unfamiliar Artists ────────────────────────
  describe("10. Discovery Exploration", () => {
    it("interleaves unfamiliar artists according to the discovery slider setting", () => {
      const familiarArtists = ["Arijit Singh", "Sid Sriram"];
      const tracks: TrackLike[] = [
        makeTrack("1", "Song 1", "Arijit Singh"),
        makeTrack("2", "Song 2", "Sid Sriram"),
        makeTrack("3", "Song 3", "Arijit Singh"),
        makeTrack("4", "Song 4", "New Indie Artist A"),
        makeTrack("5", "Song 5", "New Indie Artist B"),
        makeTrack("6", "Song 6", "New Indie Artist C"),
      ];

      // At 80% discovery, exploratory artists get prominent placement
      const highDiscovery = applyDiscoveryDistribution(tracks, familiarArtists, 80);
      const familiarFirst2High = highDiscovery.slice(0, 2).filter((t) => familiarArtists.includes(t.artist));
      expect(familiarFirst2High.length).toBeLessThanOrEqual(1);

      // At 10% discovery, familiar artists dominate
      const lowDiscovery = applyDiscoveryDistribution(tracks, familiarArtists, 10);
      const familiarFirst2Low = lowDiscovery.slice(0, 2).filter((t) => familiarArtists.includes(t.artist));
      expect(familiarFirst2Low.length).toBeGreaterThanOrEqual(1);
    });
  });

  // ─── 11. Performance Benchmark ──────────────────────────────────
  describe("11. Performance Benchmark", () => {
    it("ranks 50 candidate tracks locally well under 3 ms", () => {
      const policy = new ThompsonSamplingPolicy();
      const bench = policy.benchmarkRanking(50);
      expect(bench.count).toBe(50);
      expect(bench.durationMs).toBeLessThan(3.0);
    });
  });
});
